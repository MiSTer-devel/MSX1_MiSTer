#!/usr/bin/env python3
"""Generate msx_cpu_prog.svh: Z80 test program for msx_cpu_tb (opcodes by hand, labels resolved here)."""
import os
from collections import defaultdict

prog = []   # list of (label or None, bytes or callable(labels, pc) -> bytes)

def L(name):            prog.append((name, b''))
def B(*bs):             prog.append((None, bytes(bs)))
def W(op, lbl):         prog.append((None, lambda lb, pc, op=op, lbl=lbl: bytes(op) + lb[lbl].to_bytes(2, 'little')))
def REL(op, lbl):       prog.append((None, lambda lb, pc, op=op, lbl=lbl: bytes([op, (lb[lbl] - (pc + 2)) & 0xFF])))
def ORG(addr):          prog.append(('@org', addr))

ORG(0x0000)
B(0xF3)                         # DI
B(0x31, 0x00, 0xF0)             # LD SP,F000h
B(0xED, 0x56)                   # IM 1
B(0xAF)                         # XOR A
B(0x32, 0x00, 0xA0)             # LD (A000h),A   interrupt counter
B(0xFB)                         # EI
W([0xC3], 'main')               # JP main

ORG(0x0038)                     # IM 1 handler
B(0xF5)                         # PUSH AF
B(0xE5)                         # PUSH HL
B(0xDB, 0x40)                   # IN A,(40h)
B(0x21, 0x00, 0xA0)             # LD HL,A000h
B(0x34)                         # INC (HL)
B(0x86)                         # ADD A,(HL)
B(0x32, 0x01, 0xA0)             # LD (A001h),A
B(0xE1)                         # POP HL
B(0xF1)                         # POP AF
B(0xFB)                         # EI
B(0xED, 0x4D)                   # RETI

ORG(0x0100)
L('main')
B(0x21, 0x00, 0x80)             # LD HL,8000h
B(0x06, 0x00)                   # LD B,0  (256 passes)
L('l1')
B(0x7E)                         # LD A,(HL)
B(0x80)                         # ADD A,B
B(0x77)                         # LD (HL),A
B(0x23)                         # INC HL
B(0xD3, 0x10)                   # OUT (10h),A
B(0xDB, 0x20)                   # IN A,(20h)
B(0xAE)                         # XOR (HL)
B(0x77)                         # LD (HL),A
B(0xE5)                         # PUSH HL
W([0xCD], 'sub')                # CALL sub
B(0xE1)                         # POP HL
REL(0x10, 'l1')                 # DJNZ l1
B(0x21, 0x00, 0x80)             # LD HL,8000h
B(0x11, 0x00, 0x90)             # LD DE,9000h
B(0x01, 0x00, 0x01)             # LD BC,0100h
B(0xED, 0xB0)                   # LDIR
B(0x21, 0x00, 0x90)             # LD HL,9000h
B(0x0E, 0x30)                   # LD C,30h
B(0x06, 0x20)                   # LD B,20h
B(0xED, 0xB3)                   # OTIR
B(0x21, 0x00, 0x91)             # LD HL,9100h
B(0x0E, 0x50)                   # LD C,50h
B(0x06, 0x10)                   # LD B,10h
B(0xED, 0xB2)                   # INIR
B(0x3A, 0x00, 0xA0)             # LD A,(A000h)
B(0xED, 0x44)                   # NEG
B(0xCB, 0x27)                   # SLA A
B(0xDD, 0x21, 0x00, 0x88)       # LD IX,8800h
B(0xDD, 0x77, 0x05)             # LD (IX+5),A
B(0xDD, 0x7E, 0x05)             # LD A,(IX+5)
W([0xC3], 'main')               # JP main

L('sub')
B(0x3C)                         # INC A
B(0x08)                         # EX AF,AF'
B(0x3C)                         # INC A
B(0x08)                         # EX AF,AF'
B(0xC9)                         # RET

# Two passes: resolve labels, then emit
def assemble():
    labels, mem = {}, {}
    for pass_ in (0, 1):
        pc = 0
        for name, item in prog:
            if name == '@org':
                pc = item; continue
            if name:
                labels[name] = pc; continue
            lb = labels if pass_ == 1 else defaultdict(int, labels)
            data = item(lb, pc) if callable(item) else item
            if pass_ == 1:
                for i, b in enumerate(data):
                    mem[pc + i] = b
            pc += len(data)
    return mem

mem = assemble()
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'msx_cpu_prog.svh')
with open(out, 'w', newline='\n') as f:
    f.write('// Generated by msx_cpu_prog.py, do not edit\n')
    for a in sorted(mem):
        f.write("mem[16'h%04X] = 8'h%02X;\n" % (a, mem[a]))
print('wrote', out, len(mem), 'bytes')
