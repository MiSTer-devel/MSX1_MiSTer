#!/bin/sh
# Builds the PCM test ROM (Git Bash or WSL): data/sndNN.raw (mkraw.py) -> sounds.inc -> pcmtest.rom
#   sh build.sh [sound numbers ...]    keys 1, 2, ... in this order; default 07 09 05 (32 kB max.)
set -e
cd "$(dirname "$0")"
[ $# -gt 0 ] || set -- 07 09 05
PY=$(command -v python3 || command -v python || command -v py)
"$PY" - "$@" > sounds.inc <<'PYEOF'
import os, sys
nums = ['%02d' % int(n) for n in sys.argv[1:]]
for n in nums:
    if not os.path.exists('data/snd%s.raw' % n):
        sys.exit('missing data/snd%s.raw (python mkraw.py <Criterion ROM>)' % n)
print('; generated by build.sh')
print('NSND    EQU     %d' % len(nums))
print('SNDTAB:')
for k, n in enumerate(nums):
    print('        DW      S%d, S%dE - S%d' % (k, k, k))
line = 'sounds ' + ' '.join('%d=snd%s' % (k + 1, n) for k, n in enumerate(nums))
print('S_LIST: DB      "%s", 13, 10, 0' % line)
for k, n in enumerate(nums):
    print('S%d:     INCBIN  "data/snd%s.raw"' % (k, n))
    print('S%dE:' % k)
PYEOF
PASMO=../vdptest/pasmo.exe
[ -x "$PASMO" ] || PASMO=pasmo
"$PASMO" --bin pcmtest.asm pcmtest.rom
ls -l pcmtest.rom
